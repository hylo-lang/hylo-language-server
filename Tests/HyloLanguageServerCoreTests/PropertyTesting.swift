import Foundation
import XCTest

/// A deterministic generator of pseudo-random numbers.
///
/// - See: https://prng.di.unimi.it/splitmix64.c
struct SplitMix64: RandomNumberGenerator {

  /// The state of `self`.
  private var state: UInt64

  /// Creates an instance starting from `seed`.
  init(seed: UInt64) {
    state = seed
  }

  /// Returns the next number of the sequence.
  mutating func next() -> UInt64 {
    state &+= 0x9E37_79B9_7F4A_7C15
    var z = state
    z = (z ^ (z >> 30)) &* 0xBF58_476D_1CE4_E5B9
    z = (z ^ (z >> 27)) &* 0x94D0_49BB_1331_11EB
    return z ^ (z >> 31)
  }

}

/// The seeds of the inputs on which properties are checked, whose number is 25 unless set by the
/// environment variable `HYLO_PROPERTY_SEEDS`.
let propertySeeds: Range<UInt64> = {
  let n = ProcessInfo.processInfo.environment["HYLO_PROPERTY_SEEDS"].flatMap(UInt64.init(_:))
  return 0 ..< (n ?? 25)
}()

extension XCTestCase {

  /// Asserts that `counterexample` returns `nil` for the input generated by `generate` from each
  /// seed in `propertySeeds`, reporting the seed and a shrunk failing input otherwise.
  ///
  /// The failing input is shrunk by repeatedly replacing it with the first of its `reductions`
  /// that still fails.
  func assertHolds<Input: CustomStringConvertible>(
    for generate: (inout SplitMix64) -> Input,
    shrinkingBy reductions: (Input) -> [Input],
    _ counterexample: (Input) throws -> String?,
    file: StaticString = #filePath, line: UInt = #line
  ) rethrows {
    for seed in propertySeeds {
      var g = SplitMix64(seed: seed)
      var x = generate(&g)
      guard var d = try counterexample(x) else { continue }
      shrinking: while true {
        for y in reductions(x) {
          if let e = try counterexample(y) {
            (x, d) = (y, e)
            continue shrinking
          }
        }
        break
      }
      XCTFail("seed \(seed): \(d)\nin:\n\(x)", file: file, line: line)
    }
  }

}
